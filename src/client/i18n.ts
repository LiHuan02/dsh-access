let active: Dict = en

export function setLocale(ctx: any): void {
  try {
    ctx.effect(() => ctx.locale.register('dsh-access', { zh, en }), 'dsh-access: locale-dict')
    const apply = () => {
      const snapshot = ctx.locale.getLocale()
      active = String(snapshot?.active ?? '').toLowerCase().startsWith('zh') ? zh : en
    }
    apply()
    ctx.effect(() => ctx.locale.subscribe(apply), 'dsh-access: locale-sync')
  } catch {
    active = en
  }
}

export function t(key: string, vars?: Record<string, string | number>): string {
  let text = active[key] ?? en[key] ?? key
  if (vars) {
    for (const [name, value] of Object.entries(vars)) {
      text = text.split(`{${name}}`).join(String(value))
    }
  }
  return text
}

export function tOptional(key: string): string | undefined {
  return active[key] ?? en[key]
}

